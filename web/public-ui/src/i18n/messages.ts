export const messages = Object.fromEntries(
  supportedLocales.map((locale) => [locale, { ...baseMessages[locale], ...(supplementalMessages[locale] || {}) }]),
) as Record<Locale, Record<MessageKey, string>>

export function translate(locale: Locale, key: MessageKey): string {
  return messages[locale]?.[key] || messages.en[key] || key
}

export function localeDirection(locale: Locale): 'ltr' | 'rtl' {
  return locale === 'ar' ? 'rtl' : 'ltr'
}

export function normalizeLocale(locale: string | null | undefined): Locale {
  const value = String(locale || '').trim().replace('_', '-')
  const lower = value.toLowerCase()
  if (lower === 'zh' || lower === 'zh-cn' || lower === 'zh-hans' || lower.startsWith('zh-hans-')) return 'zh-CN'
  if (lower === 'zh-tw' || lower === 'zh-hant' || lower === 'zh-hk' || lower === 'zh-mo' || lower.startsWith('zh-hant-')) return 'zh-TW'
  if (lower === 'pt' || lower === 'pt-br') return 'pt-BR'
  const exact = supportedLocales.find((item) => item.toLowerCase() === lower)
  if (exact) return exact
  const language = lower.split('-')[0]
  const byLanguage = supportedLocales.find((item) => item.toLowerCase().split('-')[0] === language)
  if (byLanguage) return byLanguage
  return 'en'
}
